#!/usr/bin/env node
// Writes src/confusables-data.ts (#763): Unicode's UTS #39 table of look-alike characters (security/confusables.txt),
// as the characters themselves, which src/confusables.ts reads. The upstream file isn't kept in the repo. To update
// the table, download the new version's file from unicode.org and pass its path, from the repo root:
//
//   node scripts/dev/confusables-data.mjs <path to confusables.txt>
//
// then update the pins in test/confusables.test.ts (the file's version, address, sha256 and count, and the table's
// sha256) and THIRD_PARTY_NOTICES.md.
//
// WHY the characters and not the file's numbers: the table then holds no code point number that a scan of letter and
// digit runs (the denylist, the push gate) could read as a word, and a reader of the table sees the look-alike itself.
// INVARIANT: byte-identical output for a given confusables.txt. Every line of the file is a comment, a blank or a
// mapping; anything else fails, so a format change can't drop entries quietly. The output is checked to read back
// as exactly the file's mappings before it is written.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

const OUT = 'src/confusables-data.ts';
const source = process.argv[2];
if (!source) {
  console.error('usage: node scripts/dev/confusables-data.mjs <path to confusables.txt>');
  process.exit(2);
}
const bytes = readFileSync(source);
const text = bytes.toString('utf8');
const version = /^# Version: (\d+\.\d+\.\d+)$/m.exec(text)?.[1];
if (!version) throw new Error(`${source}: no "# Version:" line`);

const entries = [];
for (const [i, line] of text.split('\n').entries()) {
  // A comment may follow a byte order mark on the first line (a format character, Cf).
  if (line === '' || /^\p{Cf}*#/u.test(line)) continue;
  const m = /^([0-9A-F]{4,6}) ;\t([0-9A-F]{4,6}(?: [0-9A-F]{4,6})*) ;\tMA\t#/.exec(line);
  if (!m) throw new Error(`${source}:${i + 1}: not a comment or a mapping: ${JSON.stringify(line.slice(0, 80))}`);
  const char = (hex) => String.fromCodePoint(parseInt(hex, 16));
  entries.push([char(m[1]), m[2].split(' ').map(char).join('')]);
}
entries.sort((a, b) => a[0].codePointAt(0) - b[0].codePointAt(0));
for (let i = 1; i < entries.length; i++) if (entries[i][0] === entries[i - 1][0]) throw new Error(`${source}: mapping ${i + 1} maps a character mapped already`);
// One mapping a line, so neither side may hold a line break, and the prototype must be there.
for (const [from, to] of entries) if (/[\n\r]/.test(from + to) || !to) throw new Error(`${source}: a mapping holds a line break or maps to nothing`);

const lines = entries.map(([from, to]) => from + to);
// A template literal's own escapes: a backslash, a backquote and a ${ (no other character needs one).
const literal = lines.map((l) => l.replace(/[\\`]|\$\{/g, (s) => `\\${s}`)).join('\n');
if (literal.replace(/\\([\\`$])/g, '$1') !== lines.join('\n')) throw new Error('the escaped table does not read back as the mappings');

const sha256 = createHash('sha256').update(bytes).digest('hex');
const url = `https://www.unicode.org/Public/${version}/security/confusables.txt`;
const out = `// GENERATED by scripts/dev/confusables-data.mjs from Unicode's confusables.txt (UTS #39, #763). Don't edit it by
// hand: run the script on a newer file. The data is Copyright Unicode, Inc., under the Unicode License v3
// (THIRD_PARTY_NOTICES.md). src/confusables.ts reads it; locked with the review levels.

/** The file the table was made from: its Unicode version, where it is published, the sha256 of its bytes, its mappings. */
export const CONFUSABLES_SOURCE = { version: '${version}', url: '${url}', sha256: '${sha256}', mappings: ${entries.length} } as const;

/**
 * One mapping a line, sorted: a character, then the prototype UTS #39's skeleton maps it to, both written as
 * themselves. Some are blank, combining or line-separator characters, so read it by its \\n line breaks only.
 */
export const CONFUSABLES = \`
${literal}
\`;
`;
writeFileSync(OUT, out);
console.log(`${OUT}: ${entries.length} mappings from Unicode ${version} (${url}, sha256 ${sha256})`);
